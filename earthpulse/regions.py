"""Country polygons and the 1° country-index grid (DATA_CONTRACT.md §11).

The country grid assigns every 1° cell to the Natural Earth admin-0 country
that contains the cell **centre**. It is intentionally independent of the land
mask: cells outside the common mask keep their country index, and the mask is
applied separately by the export step (P08).

Only the standard scientific stack is used. Point-in-polygon uses
``matplotlib.path.Path`` (already a project dependency), including holes,
MultiPolygons and antimeridian-crossing rings.

Public API
----------
``build_country_grid(geojson_path)``
    Return ``(int16[180, 360], countries)``. ``countries`` is a list of
    dictionaries with ``index``, ``id``, ``label``, ``iso_numeric`` and
    ``bbox``, sorted by ISO numeric id.
``country_cells_in_mask(grid, mask)``
    Count cells of each country inside a boolean mask.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Iterable

import numpy as np
from matplotlib.path import Path as MplPath

from earthpulse.contract import (
    COUNTRY_NONE,
    LAT_NORTH_CENTER,
    LON_WEST_CENTER,
    N_COLS,
    N_ROWS,
    RESOLUTION_DEG,
)

__all__ = ["build_country_grid", "country_cells_in_mask"]


def build_country_grid(geojson_path: Path | str) -> tuple[np.ndarray, list[dict[str, Any]]]:
    """Build the contract country grid from a Natural Earth GeoJSON file.

    Args:
        geojson_path: FeatureCollection generated by
            ``scripts/p10_build_countries.mjs``. Features must have an ISO
            numeric ``id`` and ``properties.name``.

    Returns:
        ``(grid, countries)`` where ``grid`` is int16 ``(180, 360)`` with row 0
        north and value = country index or ``COUNTRY_NONE``. ``countries`` is
        sorted by ISO numeric id and each entry contains ``index``,
        ``id`` (``country_{iso}``), ``label``, ``iso_numeric`` and ``bbox``
        ``[west, south, east, north]``. All countries are returned; the export
        filters ``n_cells >= 3`` after applying the common mask.

    Raises:
        ValueError: If the file is not a FeatureCollection or a feature lacks
            the expected fields.
    """

    payload = json.loads(Path(geojson_path).read_text(encoding="utf-8"))
    if payload.get("type") != "FeatureCollection":
        raise ValueError("Expected a GeoJSON FeatureCollection")
    raw_features = payload.get("features")
    if not isinstance(raw_features, list) or not raw_features:
        raise ValueError("GeoJSON FeatureCollection has no features")

    prepared: list[tuple[str, str, Any]] = []
    for feature in raw_features:
        geometry = feature.get("geometry")
        if not geometry:
            continue
        iso = str(feature.get("id", "")).strip()
        name = (feature.get("properties") or {}).get("name")
        if not iso or not name:
            raise ValueError(
                "Country features need an ISO numeric id and properties.name"
            )
        prepared.append((iso.zfill(3), str(name), geometry))
    prepared.sort(key=lambda item: item[0])

    grid = np.full((N_ROWS, N_COLS), COUNTRY_NONE, dtype=np.int16)
    countries: list[dict[str, Any]] = []

    row_lats = LAT_NORTH_CENTER - np.arange(N_ROWS, dtype=float) * RESOLUTION_DEG
    col_lons = LON_WEST_CENTER + np.arange(N_COLS, dtype=float) * RESOLUTION_DEG

    for iso_numeric, name, geometry in prepared:
        polygons = list(_polygons(geometry))
        if not polygons:
            continue
        index = len(countries)

        all_lons: list[float] = []
        all_lats: list[float] = []
        for rings in polygons:
            exterior = np.asarray(rings[0], dtype=float)
            all_lons.extend(exterior[:, 0].tolist())
            all_lats.extend(exterior[:, 1].tolist())

            _assign_polygon(
                grid, index, exterior, rings[1:], row_lats, col_lons
            )

        bbox = [
            round(float(min(all_lons)), 4),
            round(float(min(all_lats)), 4),
            round(float(max(all_lons)), 4),
            round(float(max(all_lats)), 4),
        ]
        countries.append(
            {
                "index": index,
                "id": f"country_{iso_numeric}",
                "label": name,
                "iso_numeric": iso_numeric,
                "bbox": bbox,
            }
        )

    return grid, countries


def country_cells_in_mask(
    grid: np.ndarray, mask: np.ndarray
) -> dict[int, int]:
    """Count the cells of each country that fall inside ``mask``.

    Args:
        grid: int array ``(180, 360)`` from :func:`build_country_grid`.
        mask: boolean array of the same shape (the common land mask).

    Returns:
        ``{country_index: n_cells}`` for countries with at least one masked
        cell. Negative indices (no country) are ignored.
    """

    grid_array = np.asarray(grid)
    mask_array = np.asarray(mask, dtype=bool)
    if grid_array.shape != (N_ROWS, N_COLS):
        raise ValueError(
            f"grid must have shape {(N_ROWS, N_COLS)}, got {grid_array.shape}"
        )
    if mask_array.shape != grid_array.shape:
        raise ValueError(
            f"mask must have shape {grid_array.shape}, got {mask_array.shape}"
        )

    selected = grid_array[mask_array]
    selected = selected[selected >= 0]
    if selected.size == 0:
        return {}
    values, counts = np.unique(selected, return_counts=True)
    return {int(value): int(count) for value, count in zip(values, counts)}


# ---------------------------------------------------------------------------
# Geometry helpers
# ---------------------------------------------------------------------------


def _polygons(geometry: dict[str, Any]) -> Iterable[list[list[list[float]]]]:
    """Yield each polygon as ``[exterior_ring, hole, ...]``."""

    geometry_type = geometry.get("type")
    coordinates = geometry.get("coordinates")
    if geometry_type == "Polygon":
        yield coordinates
    elif geometry_type == "MultiPolygon":
        for polygon in coordinates:
            yield polygon
    else:
        return


def _unwrap_ring(ring: list[list[float]]) -> np.ndarray:
    """Return a ring with continuous longitudes (no ±180 jumps)."""

    points = np.asarray(ring, dtype=float)
    if points.shape[0] < 4:
        return points
    unwrapped = points.copy()
    for row in range(1, unwrapped.shape[0]):
        previous = unwrapped[row - 1, 0]
        lon = unwrapped[row, 0]
        while lon - previous > 180.0:
            lon -= 360.0
        while lon - previous < -180.0:
            lon += 360.0
        unwrapped[row, 0] = lon
    return unwrapped


def _align_hole(exterior: np.ndarray, hole: np.ndarray) -> np.ndarray:
    """Shift an unwrapped hole by whole turns to sit near the exterior."""

    shift = round((float(exterior[:, 0].mean()) - float(hole[:, 0].mean())) / 360.0)
    aligned = hole.copy()
    aligned[:, 0] += shift * 360.0
    return aligned


def _assign_polygon(
    grid: np.ndarray,
    index: int,
    exterior: np.ndarray,
    holes: list[list[list[float]]],
    row_lats: np.ndarray,
    col_lons: np.ndarray,
) -> None:
    """Assign grid cells whose centres fall inside one polygon."""

    ext = _unwrap_ring(exterior.tolist())
    if ext.shape[0] < 4:
        return
    hole_rings = [
        _align_hole(ext, _unwrap_ring(hole)) for hole in holes
    ]
    ext_path = MplPath(ext, closed=True)
    hole_paths = [MplPath(hole, closed=True) for hole in hole_rings]

    lat_min = float(ext[:, 1].min())
    lat_max = float(ext[:, 1].max())
    row0 = max(0, math.ceil((LAT_NORTH_CENTER - lat_max) / RESOLUTION_DEG))
    row1 = min(N_ROWS - 1, math.floor((LAT_NORTH_CENTER - lat_min) / RESOLUTION_DEG))
    if row0 > row1:
        return
    rows = np.arange(row0, row1 + 1, dtype=int)

    lon_min = float(ext[:, 0].min())
    lon_max = float(ext[:, 0].max())
    for shift in (-360.0, 0.0, 360.0):
        west = lon_min - shift
        east = lon_max - shift
        col0 = max(0, math.ceil((west - LON_WEST_CENTER) / RESOLUTION_DEG))
        col1 = min(N_COLS - 1, math.floor((east - LON_WEST_CENTER) / RESOLUTION_DEG))
        if col0 > col1:
            continue
        cols = np.arange(col0, col1 + 1, dtype=int)
        if rows.size == 0 or cols.size == 0:
            continue

        rows_grid = np.repeat(rows, cols.size)
        cols_grid = np.tile(cols, rows.size)
        points = np.column_stack(
            [col_lons[cols_grid] + shift, row_lats[rows_grid]]
        )
        inside = ext_path.contains_points(points)
        for hole_path in hole_paths:
            inside &= ~hole_path.contains_points(points)
        if not inside.any():
            continue

        target = grid[rows_grid[inside], cols_grid[inside]]
        unassigned = target == COUNTRY_NONE
        if unassigned.any():
            grid[rows_grid[inside][unassigned], cols_grid[inside][unassigned]] = index
